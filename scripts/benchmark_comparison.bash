#!/bin/bash
# =============================================================================
# benchmark_comparison.bash - Benchmarks comparativos con múltiples backends
# =============================================================================
# Uso: bash scripts/benchmark_comparison.bash [compiler] [mode] [iterations] [cxx_override]
#
# Compara rendimiento de:
#   - nstd::uint128_t / nstd::int128_t (este proyecto)
#   - unsigned __int128 / __int128 (GCC/Clang builtin)
#   - boost::multiprecision::uint128_t (cpp_int backend, si disponible)
#   - Tipos builtin (uint64_t, int64_t) como baseline
#
# Requisitos (Boost, opcional):
#   pacman -S mingw-w64-ucrt-x86_64-boost
#
# Ejemplos:
#   bash scripts/benchmark_comparison.bash gcc release-O3
#   bash scripts/benchmark_comparison.bash clang release-Ofast 5000000
# =============================================================================

set -e

# Colores
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m'

# Parámetros
COMPILER="${1:-gcc}"
MODE="${2:-release-O3}"
ITERATIONS="${3:-5000000}"
CXX_OVERRIDE="${4:-}"   # ruta explícita al compilador (pasada desde make.py)

# Directorio del proyecto
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(dirname "$SCRIPT_DIR")"
cd "$PROJECT_ROOT"

# Crear directorio de benchmarks
BUILD_DIR="build/benchmark_comparison/${COMPILER}/${MODE}"
mkdir -p "$BUILD_DIR"

TIMESTAMP=$(date +%Y%m%d_%H%M%S)
RESULT_FILE="$BUILD_DIR/results_${TIMESTAMP}.txt"

# Flags según modo
get_mode_flags() {
    case "$MODE" in
        debug)         echo "-O0 -g" ;;
        release)       echo "-O2" ;;
        release-O1)    echo "-O1" ;;
        release-O2)    echo "-O2" ;;
        release-O3)    echo "-O3 -fexpensive-optimizations -funroll-loops -ftree-vectorize -march=native" ;;
        release-Ofast) echo "-Ofast -ffast-math -fexpensive-optimizations -march=native" ;;
        *)             echo "-O2" ;;
    esac
}

# Verificar Boost
check_boost() {
    local test_file
    test_file=$(mktemp --suffix=.cpp)
    cat > "$test_file" << 'EOF'
#include <boost/multiprecision/cpp_int.hpp>
int main() {
    boost::multiprecision::uint128_t x = 42;
    return 0;
}
EOF
    if g++ -std=c++20 "$test_file" -o /dev/null 2>/dev/null; then
        rm -f "$test_file"
        return 0
    else
        rm -f "$test_file"
        return 1
    fi
}

# Crear archivo de benchmark
# Usa bench_common.hpp para RDTSC + doNotOptimize (igual que los benchmarks del proyecto).
# BENCH_ITERATIONS se pasa vía -D en la línea de compilación (no se necesita sed).
create_benchmark_source() {
    cat > "$BUILD_DIR/benchmark_comparison.cpp" << 'BENCHMARK_EOF'
// Generated by benchmark_comparison.bash
// Infrastructure: bench_common.hpp (RDTSC cycle counter + doNotOptimize)

#include "int128_parameterized.hpp"
#include "bench_common.hpp"

#ifdef HAS_BOOST
#include <boost/multiprecision/cpp_int.hpp>
namespace bmp = boost::multiprecision;
#endif

#ifdef __SIZEOF_INT128__
#define HAS_BUILTIN_INT128 1
#endif

using namespace nstd;

// ============================================================================
// Benchmark templates
// Each function runs WARMUP + ITERATIONS cycles measured with RDTSC.
// doNotOptimize() prevents dead-code elimination without introducing
// unnecessary memory traffic (see bench_common.hpp for compiler-specific impl).
// ============================================================================

template <typename T>
static BenchResult bench_add(const char* name) {
    T a = static_cast<T>(0xDEADBEEF12345678ull);
    T b = static_cast<T>(0x1234567890ABCDEFull);
    for (std::size_t i = 0; i < WARMUP; ++i)    { a += b; doNotOptimize(a); }
    CycleTimer t;
    for (std::size_t i = 0; i < ITERATIONS; ++i) { a += b; doNotOptimize(a); }
    return {name, static_cast<double>(t.elapsed_cycles()) / ITERATIONS};
}

template <typename T>
static BenchResult bench_sub(const char* name) {
    T a = static_cast<T>(0xDEADBEEF12345678ull);
    T b = static_cast<T>(0x1234567890ABCDEFull);
    for (std::size_t i = 0; i < WARMUP; ++i)    { a -= b; doNotOptimize(a); }
    CycleTimer t;
    for (std::size_t i = 0; i < ITERATIONS; ++i) { a -= b; doNotOptimize(a); }
    return {name, static_cast<double>(t.elapsed_cycles()) / ITERATIONS};
}

template <typename T>
static BenchResult bench_mul(const char* name) {
    // Use result + 1 as next dividend to prevent constant folding while
    // keeping values in a realistic range (wrapping is fine for a benchmark).
    T a = static_cast<T>(123456789ull);
    T b = static_cast<T>(987654321ull);
    for (std::size_t i = 0; i < WARMUP; ++i) {
        T r = a * b; doNotOptimize(r); a = r + static_cast<T>(1);
    }
    CycleTimer t;
    for (std::size_t i = 0; i < ITERATIONS; ++i) {
        T r = a * b; doNotOptimize(r); a = r + static_cast<T>(1);
    }
    return {name, static_cast<double>(t.elapsed_cycles()) / ITERATIONS};
}

template <typename T>
static BenchResult bench_div(const char* name) {
    // Dividend grows by b each iteration — avoids constant-divisor hoisting.
    T a = static_cast<T>(1000000000000000001ull);
    T b = static_cast<T>(12345ull);
    for (std::size_t i = 0; i < WARMUP; ++i) {
        T r = a / b; doNotOptimize(r); a += b;
    }
    CycleTimer t;
    for (std::size_t i = 0; i < ITERATIONS; ++i) {
        T r = a / b; doNotOptimize(r); a += b;
    }
    return {name, static_cast<double>(t.elapsed_cycles()) / ITERATIONS};
}

template <typename T>
static BenchResult bench_xor(const char* name) {
    T a = static_cast<T>(0x5EADBEEF5EADBEEFull);
    T b = static_cast<T>(0x4AFEBABE4AFEBABEull);
    for (std::size_t i = 0; i < WARMUP; ++i)    { a ^= b; doNotOptimize(a); }
    CycleTimer t;
    for (std::size_t i = 0; i < ITERATIONS; ++i) { a ^= b; doNotOptimize(a); }
    return {name, static_cast<double>(t.elapsed_cycles()) / ITERATIONS};
}

template <typename T>
static BenchResult bench_cmp(const char* name) {
    // a < b is true throughout (a grows by 1 per iter; starts 10^18 below b).
    T a = static_cast<T>(1000000000000000001ull);
    T b = static_cast<T>(2000000000000000003ull);
    volatile bool r = false;
    for (std::size_t i = 0; i < WARMUP; ++i) {
        r = (a < b); a += static_cast<T>(1); doNotOptimize(a);
    }
    CycleTimer t;
    for (std::size_t i = 0; i < ITERATIONS; ++i) {
        r = (a < b); a += static_cast<T>(1); doNotOptimize(a);
    }
    return {name, static_cast<double>(t.elapsed_cycles()) / ITERATIONS};
}

// ============================================================================
// MAIN
// ============================================================================

int main() {
    std::cout << "============================================================\n";
    std::cout << "  BENCHMARK COMPARATIVO - int128 vs __int128 vs Boost\n";
    std::cout << "============================================================\n";
    std::cout << "  Iterations: " << ITERATIONS << " | Warmup: " << WARMUP << "\n";
    std::cout << "============================================================\n";

    double base;
    BenchResult r{"", 0.0};

    // --- Addition (+) ---
    print_header("Addition (+)");
    r = bench_add<std::uint64_t>("uint64_t");            base = r.cycles_per_op; print_result(r, base);
    print_result(bench_add<uint128_t>("nstd::uint128_t"),  base);
    print_result(bench_add<int128_t>("nstd::int128_t"),    base);
#ifdef HAS_BUILTIN_INT128
    print_result(bench_add<unsigned __int128>("u __int128"), base);
    print_result(bench_add<__int128>("__int128"),           base);
#endif
#ifdef HAS_BOOST
    print_result(bench_add<bmp::uint128_t>("boost::u128"), base);
#endif
    print_footer();

    // --- Subtraction (-) ---
    print_header("Subtraction (-)");
    r = bench_sub<std::uint64_t>("uint64_t");            base = r.cycles_per_op; print_result(r, base);
    print_result(bench_sub<uint128_t>("nstd::uint128_t"),  base);
    print_result(bench_sub<int128_t>("nstd::int128_t"),    base);
#ifdef HAS_BUILTIN_INT128
    print_result(bench_sub<unsigned __int128>("u __int128"), base);
    print_result(bench_sub<__int128>("__int128"),           base);
#endif
#ifdef HAS_BOOST
    print_result(bench_sub<bmp::uint128_t>("boost::u128"), base);
#endif
    print_footer();

    // --- Multiplication (*) ---
    print_header("Multiplication (*)");
    r = bench_mul<std::uint64_t>("uint64_t");            base = r.cycles_per_op; print_result(r, base);
    print_result(bench_mul<uint128_t>("nstd::uint128_t"),  base);
    print_result(bench_mul<int128_t>("nstd::int128_t"),    base);
#ifdef HAS_BUILTIN_INT128
    print_result(bench_mul<unsigned __int128>("u __int128"), base);
    print_result(bench_mul<__int128>("__int128"),           base);
#endif
#ifdef HAS_BOOST
    print_result(bench_mul<bmp::uint128_t>("boost::u128"), base);
#endif
    print_footer();

    // --- Division (/, unsigned only) ---
    print_header("Division (/, unsigned)");
    r = bench_div<std::uint64_t>("uint64_t");            base = r.cycles_per_op; print_result(r, base);
    print_result(bench_div<uint128_t>("nstd::uint128_t"),  base);
#ifdef HAS_BUILTIN_INT128
    print_result(bench_div<unsigned __int128>("u __int128"), base);
#endif
#ifdef HAS_BOOST
    print_result(bench_div<bmp::uint128_t>("boost::u128"), base);
#endif
    print_footer();

    // --- Bitwise XOR (^) ---
    print_header("Bitwise XOR (^)");
    r = bench_xor<std::uint64_t>("uint64_t");            base = r.cycles_per_op; print_result(r, base);
    print_result(bench_xor<uint128_t>("nstd::uint128_t"),  base);
    print_result(bench_xor<int128_t>("nstd::int128_t"),    base);
#ifdef HAS_BUILTIN_INT128
    print_result(bench_xor<unsigned __int128>("u __int128"), base);
    print_result(bench_xor<__int128>("__int128"),           base);
#endif
#ifdef HAS_BOOST
    print_result(bench_xor<bmp::uint128_t>("boost::u128"), base);
#endif
    print_footer();

    // --- Comparison (<) ---
    print_header("Comparison (<)");
    r = bench_cmp<std::uint64_t>("uint64_t");            base = r.cycles_per_op; print_result(r, base);
    print_result(bench_cmp<uint128_t>("nstd::uint128_t"),  base);
    print_result(bench_cmp<int128_t>("nstd::int128_t"),    base);
#ifdef HAS_BUILTIN_INT128
    print_result(bench_cmp<unsigned __int128>("u __int128"), base);
    print_result(bench_cmp<__int128>("__int128"),           base);
#endif
#ifdef HAS_BOOST
    print_result(bench_cmp<bmp::uint128_t>("boost::u128"), base);
#endif
    print_footer();

    std::cout << "\n============================================================\n";
    std::cout << "  BENCHMARK COMPLETED\n";
    std::cout << "============================================================\n";

    return 0;
}
BENCHMARK_EOF
}

# =============================================================================
# MAIN
# =============================================================================
echo -e "${BLUE}============================================================${NC}"
echo -e "${BLUE}  BENCHMARK COMPARATIVO${NC}"
echo -e "${BLUE}============================================================${NC}"
echo -e "  Compilador:   ${GREEN}$COMPILER${NC}"
echo -e "  Modo:         ${GREEN}$MODE${NC}"
echo -e "  Iteraciones:  ${GREEN}$ITERATIONS${NC}"
echo -e "${BLUE}------------------------------------------------------------${NC}"

# Verificar Boost
HAS_BOOST=0
if check_boost; then
    echo -e "  Boost:        ${GREEN}Detectado${NC}"
    HAS_BOOST=1
else
    echo -e "  Boost:        ${YELLOW}No encontrado (instalar: pacman -S mingw-w64-ucrt-x86_64-boost)${NC}"
fi

# Crear fuente
create_benchmark_source

# Compilar
MODE_FLAGS=$(get_mode_flags "$MODE")
if [[ -n "$CXX_OVERRIDE" ]]; then
    COMPILER_CMD="$CXX_OVERRIDE"
else
    COMPILER_CMD="g++"
    [[ "$COMPILER" == "clang" ]] && COMPILER_CMD="clang++"
fi

DEFINES="-DBENCH_ITERATIONS=${ITERATIONS}"
[[ $HAS_BOOST -eq 1 ]] && DEFINES="$DEFINES -DHAS_BOOST"

OUTPUT="$BUILD_DIR/benchmark_comparison"

echo -e "${BLUE}------------------------------------------------------------${NC}"
echo -e "  Compilando..."

CMD="$COMPILER_CMD -std=c++20 $MODE_FLAGS -I include -I benchs $DEFINES $BUILD_DIR/benchmark_comparison.cpp -o $OUTPUT"
echo -e "  ${YELLOW}$CMD${NC}"

if eval "$CMD"; then
    echo -e "${GREEN}[OK] Compilación exitosa${NC}"
else
    echo -e "${RED}[FAIL] Error de compilación${NC}"
    exit 1
fi

# Ejecutar
echo -e "${BLUE}------------------------------------------------------------${NC}"
echo -e "  Ejecutando benchmark..."
echo ""

"$OUTPUT" | tee "$RESULT_FILE"

echo ""
echo -e "${GREEN}[OK] Resultados guardados en: $RESULT_FILE${NC}"
